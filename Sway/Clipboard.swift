import AppKit
import SwiftUI

/// A small, private clipboard history. Event-driven: the pasteboard is read
/// only right after a copy Sway can see (⌘C/⌘X through its own event tap, its
/// own Copy and Cut actions, an app switch, or opening the history) and never
/// on a timer. It runs only while a clipboard-history action is assigned,
/// keeps text in memory only, and skips anything a password manager marks.
final class ClipboardHistory {
    static let shared = ClipboardHistory()
    static let capacity = 12
    static let maximumLength = 100_000
    /// The nspasteboard.org markers that password managers and clipboard
    /// tools set on secrets and one-off data.
    static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]

    /// Newest first.
    private(set) var items: [String] = []
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var pendingCheck: DispatchWorkItem?
    private var activationObserver: NSObjectProtocol?

    var isEnabled = false {
        didSet {
            guard isEnabled != oldValue else { return }
            if isEnabled {
                lastChangeCount = NSPasteboard.general.changeCount
                activationObserver = NSWorkspace.shared.notificationCenter.addObserver(
                    forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main) { [weak self] _ in
                        self?.check()
                    }
            } else {
                // Turning it off forgets everything immediately.
                items.removeAll()
                pendingCheck?.cancel()
                pendingCheck = nil
                if let activationObserver { NSWorkspace.shared.notificationCenter.removeObserver(activationObserver) }
                activationObserver = nil
            }
        }
    }

    // MARK: Pure rules

    static func shouldRecord(types: [String], text: String?) -> Bool {
        guard let text, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.utf16.count <= maximumLength else { return false }
        return privateTypes.isDisjoint(with: types)
    }

    /// Most recent first, without duplicates, at most `capacity` items.
    static func inserting(_ text: String, into items: [String], capacity: Int = capacity) -> [String] {
        Array(([text] + items.filter { $0 != text }).prefix(max(1, capacity)))
    }

    /// One-line preview for the picker.
    static func preview(_ text: String, limit: Int = 90) -> String {
        let flattened = text.split(whereSeparator: \.isNewline).map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty }.joined(separator: " ⏎ ")
        return flattened.count > limit ? String(flattened.prefix(limit - 1)) + "…" : flattened
    }

    // MARK: Capture

    /// Apps update the pasteboard just after the shortcut; read once, shortly after.
    func noteCopy(after delay: Double = 0.15) {
        guard isEnabled else { return }
        pendingCheck?.cancel()
        let work = DispatchWorkItem { [weak self] in self?.check() }
        pendingCheck = work
        DispatchQueue.main.asyncAfter(deadline: .now() + delay, execute: work)
    }

    func check() {
        guard isEnabled else { return }
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        let types = pasteboard.types?.map(\.rawValue) ?? []
        let text = pasteboard.string(forType: .string)
        guard Self.shouldRecord(types: types, text: text), let text else { return }
        items = Self.inserting(text, into: items)
    }

    // MARK: Paste

    /// Puts the item on the clipboard and sends ⌘V to the app that was in
    /// front when the gesture began.
    @discardableResult
    func paste(_ text: String, into application: pid_t) -> Bool {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        guard pasteboard.setString(text, forType: .string) else { return false }
        lastChangeCount = pasteboard.changeCount
        items = Self.inserting(text, into: items)
        guard let command = EdgeCommand.resolve(.paste, increasing: true) else { return false }
        return EdgeActionController.send(command, expectedApplication: application)
    }

    /// The item copied before the current one.
    @discardableResult
    func pastePrevious(into application: pid_t) -> Bool {
        check()
        guard items.count > 1 else {
            OSDOverlay.shared.show(type: .message("Nothing earlier to paste yet", icon: "list.clipboard"), value: 1)
            return true
        }
        return paste(items[1], into: application)
    }
}

/// The picker shown while swiping through history. Lifting pastes the
/// highlighted item; a rejected or cancelled gesture pastes nothing.
final class ClipboardHUD {
    static let shared = ClipboardHUD()
    private var panel: NSPanel?
    private let model = ClipboardPickerModel()
    private(set) var isActive = false

    var selectedText: String? {
        model.items.indices.contains(model.selection) ? model.items[model.selection] : nil
    }

    /// Opens at the previous item (the current one is a normal paste).
    func begin() {
        ClipboardHistory.shared.check()
        model.items = ClipboardHistory.shared.items
        model.selection = min(1, max(0, model.items.count - 1))
        isActive = true
        show()
    }

    /// Up is newer, down is older.
    func move(newer: Bool) {
        guard isActive, !model.items.isEmpty else { return }
        model.selection = min(model.items.count - 1, max(0, model.selection + (newer ? -1 : 1)))
    }

    func end() {
        isActive = false
        panel?.orderOut(nil)
        panel?.contentView = nil
    }

    private func show() {
        let host = NSHostingView(rootView: ClipboardPickerView(model: model)
            .preferredColorScheme(TrackpadSettings.shared.resolvedColorScheme))
        let panel = self.panel ?? {
            let panel = NSPanel(contentRect: .zero, styleMask: [.borderless, .nonactivatingPanel], backing: .buffered, defer: true)
            panel.isOpaque = false
            panel.backgroundColor = .clear
            panel.hasShadow = true
            panel.level = .statusBar
            panel.ignoresMouseEvents = true
            panel.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary, .ignoresCycle]
            panel.isReleasedWhenClosed = false
            return panel
        }()
        panel.appearance = TrackpadSettings.shared.themeAppearance
        panel.contentView = host
        let size = NSSize(width: 420, height: host.fittingSize.height)
        panel.setContentSize(size)
        let screen = NSScreen.screens.first { NSMouseInRect(NSEvent.mouseLocation, $0.frame, false) } ?? NSScreen.main
        if let frame = screen?.visibleFrame {
            panel.setFrameOrigin(NSPoint(x: frame.midX - size.width / 2, y: frame.midY - size.height / 2))
        }
        panel.orderFrontRegardless()
        self.panel = panel
    }
}

final class ClipboardPickerModel: ObservableObject {
    @Published var items: [String] = []
    @Published var selection = 0
}

private struct ClipboardPickerView: View {
    @ObservedObject var model: ClipboardPickerModel
    @Environment(\.accessibilityReduceTransparency) private var reduceTransparency

    var body: some View {
        VStack(alignment: .leading, spacing: 10) {
            HStack {
                Label("Clipboard", systemImage: "list.clipboard").font(.system(size: 13, weight: .semibold))
                Spacer()
                if !model.items.isEmpty {
                    Text("\(model.selection + 1) of \(model.items.count)").font(.system(size: 11)).monospacedDigit().foregroundStyle(.secondary)
                }
            }
            if model.items.isEmpty {
                Text("Copy something, and it appears here. Sway keeps up to \(ClipboardHistory.capacity) items in memory only.")
                    .font(.system(size: 12)).foregroundStyle(.secondary).fixedSize(horizontal: false, vertical: true)
            } else {
                // A window of five rows keeps the picker small and steady.
                let start = max(0, min(model.selection - 2, model.items.count - 5))
                ForEach(Array(model.items.enumerated()).dropFirst(start).prefix(5), id: \.offset) { index, item in
                    HStack(spacing: 10) {
                        Text(index == 0 ? "Now" : "\(index)").font(.system(size: 10, weight: .semibold)).monospacedDigit()
                            .foregroundStyle(.secondary).frame(width: 28, alignment: .leading)
                        Text(ClipboardHistory.preview(item)).font(.system(size: 13)).lineLimit(1)
                        Spacer(minLength: 0)
                    }
                    .padding(.horizontal, 10).padding(.vertical, 8)
                    .background(index == model.selection ? Color.primary.opacity(0.12) : .clear, in: RoundedRectangle(cornerRadius: 9))
                }
                Text("Swipe to choose · lift to paste").font(.system(size: 11)).foregroundStyle(.secondary)
            }
        }
        .padding(16)
        .frame(width: 420)
        .background(surface)
        .accessibilityElement(children: .combine)
        .accessibilityLabel("Clipboard history")
    }

    @ViewBuilder private var surface: some View {
        if reduceTransparency {
            RoundedRectangle(cornerRadius: 22).fill(Color(nsColor: .windowBackgroundColor))
        } else {
            RoundedRectangle(cornerRadius: 22).fill(.regularMaterial)
        }
    }
}
